import type { jsPDF } from 'jspdf';

/** Small drawing helpers over jsPDF (no autotable plugin; tables are drawn by hand like v1). */

export type Rgb = readonly [number, number, number];

export const COLORS = {
  primary: [139, 92, 246],
  green: [16, 185, 129],
  red: [239, 68, 68],
  blue: [59, 130, 246],
  text: [31, 41, 55],
  muted: [100, 100, 100],
  faint: [150, 150, 150],
  track: [225, 225, 230],
  card: [245, 245, 247],
} as const satisfies Record<string, Rgb>;

export const MARGIN = 15;

/** Hex `#10a37f` → RGB. */
export function hexToRgb(hex: string): Rgb {
  const n = Number.parseInt(hex.replace('#', ''), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

/**
 * The built-in PDF fonts only cover Latin-1, so typographic punctuation is mapped to ASCII and
 * anything else outside Latin-1 becomes `?` instead of garbage glyphs.
 */
export function pdfText(text: string): string {
  return text
    .replace(/[\u2018\u2019\u201a\u2032]/g, "'")
    .replace(/[\u201c\u201d\u201e\u2033]/g, '"')
    .replace(/[\u2013\u2014\u2212]/g, '-')
    .replace(/\u2026/g, '...')
    .replace(/[\u00a0\u2009\u202f]/g, ' ')
    .replace(/\s+/g, ' ')
    .replace(/[^\x20-\x7e\xa0-\xff]/g, '?');
}

/** Cuts `text` with `...` so it fits in `maxWidth` mm at the current font size. */
export function fit(pdf: jsPDF, text: string, maxWidth: number): string {
  const clean = pdfText(text);
  if (pdf.getTextWidth(clean) <= maxWidth) return clean;
  let lo = 0;
  let hi = clean.length;
  while (lo < hi) {
    const mid = Math.ceil((lo + hi) / 2);
    if (pdf.getTextWidth(`${clean.slice(0, mid)}...`) <= maxWidth) lo = mid;
    else hi = mid - 1;
  }
  return `${clean.slice(0, lo).trimEnd()}...`;
}

/** A vertical cursor that adds pages as content runs past the bottom margin. */
export class Cursor {
  y = MARGIN;
  constructor(private readonly pdf: jsPDF) {}

  get pageWidth(): number {
    return this.pdf.internal.pageSize.getWidth();
  }
  get pageHeight(): number {
    return this.pdf.internal.pageSize.getHeight();
  }
  get contentWidth(): number {
    return this.pageWidth - 2 * MARGIN;
  }

  /** Starts a new page when fewer than `space` mm are left (leaves room for the footer). */
  ensure(space: number): boolean {
    if (this.y + space > this.pageHeight - MARGIN - 6) {
      this.pdf.addPage();
      this.y = MARGIN;
      return true;
    }
    return false;
  }
}

export function setColor(pdf: jsPDF, rgb: Rgb): void {
  pdf.setTextColor(rgb[0], rgb[1], rgb[2]);
}

export function fill(pdf: jsPDF, rgb: Rgb): void {
  pdf.setFillColor(rgb[0], rgb[1], rgb[2]);
}

export function heading(pdf: jsPDF, cur: Cursor, text: string): void {
  cur.ensure(24);
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(14);
  setColor(pdf, COLORS.text);
  pdf.text(pdfText(text), MARGIN, cur.y);
  pdf.setFont('helvetica', 'normal');
  cur.y += 8;
}

export interface BarRow {
  label: string;
  /** 0–100. */
  value: number;
  /** Right-hand text, e.g. `42% (11/26)`. */
  text: string;
  color: Rgb;
}

/** v1 progress-bar rows: label, track, filled part, percentage. */
export function barRows(pdf: jsPDF, cur: Cursor, rows: BarRow[]): void {
  const labelWidth = 48;
  const textWidth = 30;
  const barWidth = cur.contentWidth - labelWidth - textWidth - 4;
  for (const row of rows) {
    cur.ensure(10);
    pdf.setFontSize(10);
    setColor(pdf, COLORS.text);
    pdf.text(fit(pdf, row.label, labelWidth - 4), MARGIN + 2, cur.y);
    const x = MARGIN + labelWidth;
    fill(pdf, COLORS.track);
    pdf.rect(x, cur.y - 4, barWidth, 5, 'F');
    fill(pdf, row.color);
    pdf.rect(x, cur.y - 4, (Math.max(0, Math.min(100, row.value)) / 100) * barWidth, 5, 'F');
    pdf.setFontSize(9);
    setColor(pdf, row.color);
    pdf.text(pdfText(row.text), x + barWidth + 3, cur.y);
    cur.y += 9;
  }
  cur.y += 4;
}

/** Footer on every page: product name and page numbers. */
export function footers(pdf: jsPDF): void {
  const pages = pdf.getNumberOfPages();
  const width = pdf.internal.pageSize.getWidth();
  const y = pdf.internal.pageSize.getHeight() - 8;
  for (let i = 1; i <= pages; i++) {
    pdf.setPage(i);
    pdf.setFontSize(8);
    setColor(pdf, COLORS.faint);
    pdf.text('Generated by PromptVerse - AI Visibility Analysis Platform', width / 2, y, {
      align: 'center',
    });
    pdf.text(`${i} / ${pages}`, width - MARGIN, y, { align: 'right' });
  }
}
