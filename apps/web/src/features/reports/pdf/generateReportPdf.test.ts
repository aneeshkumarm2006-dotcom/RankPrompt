import type * as JsPdf from 'jspdf';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { publicReportFixture } from '../__fixtures__/publicReport';
import { fromPublicReport, type ReportViewModel } from '../viewModel';
import { generateReportPdf } from './generateReportPdf';
import { pdfText } from './pdfKit';
import { PDF_MAX_ROWS } from './pdfResults';

const saved = vi.hoisted(() => [] as { name: string; source: string }[]);

// Capture what would be downloaded instead of saving a file.
vi.mock('jspdf', async (importOriginal) => {
  const mod = await importOriginal<typeof JsPdf>();
  class TestPdf extends mod.jsPDF {
    constructor(...args: ConstructorParameters<typeof mod.jsPDF>) {
      super(...args);
      this.save = ((name: string) => {
        saved.push({ name, source: this.output() });
        return this;
      }) as unknown as typeof this.save;
    }
  }
  return { ...mod, jsPDF: TestPdf, default: TestPdf };
});

/** Runs the generator and returns the raw PDF source it would have saved. */
async function render(report: ReportViewModel): Promise<{ name: string; source: string }> {
  await generateReportPdf(report);
  const out = saved.at(-1);
  if (!out) throw new Error('nothing saved');
  return out;
}

afterEach(() => {
  saved.length = 0;
});

describe('generateReportPdf', () => {
  it('draws the report with the PromptVerse footer and says all rows are included', async () => {
    const { name, source } = await render(fromPublicReport(publicReportFixture()));
    expect(name).toBe('Acme_Visibility_Report.pdf');
    expect(source).toContain('Generated by PromptVerse');
    expect(source).not.toContain('RankPrompt');
    expect(source).toContain('All 4 results included.');
    expect(source).toContain('(1/3)');
  });

  it('says how many rows are included out of how many when it truncates', async () => {
    const base = fromPublicReport(publicReportFixture());
    const one = base.checks[0]!;
    const checks = Array.from({ length: PDF_MAX_ROWS + 50 }, (_, i) => ({
      ...one,
      key: String(i),
      promptKey: `p${i}`,
      prompt: `Prompt ${i}`,
    }));
    const { source } = await render({ ...base, checks });
    expect(source).toContain(`Showing ${PDF_MAX_ROWS} of ${PDF_MAX_ROWS + 50} results.`);
  });
});

describe('pdfText', () => {
  it('maps typographic punctuation to ASCII and drops glyphs the PDF font lacks', () => {
    expect(pdfText('It’s “best” — really…')).toBe('It\'s "best" - really...');
    expect(pdfText('Café 日本')).toBe('Café ??');
  });
});
